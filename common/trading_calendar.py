"""A 股交易日历 —— 全项目唯一数据源（消除跨模块重复）。

原 wyckoff-auto/config.py 与 stockexpert-daily-brief/web_brief.py 各存一份，
易出现"只改一处"的同步炸弹。现统一到此模块，两处改为引用本模块。

休市日期来源：沪深北交易所 2025-12-22 公告（证券时报等转载核对一致）。
注意：2027 年及以后需按当年公告补充，否则对应节假日仍会触发生成。
"""
from __future__ import annotations

import datetime as dt

HOLIDAYS_2026 = {
    # 元旦
    "2026-01-01", "2026-01-02", "2026-01-03",
    # 春节
    "2026-02-15", "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19",
    "2026-02-20", "2026-02-21", "2026-02-22", "2026-02-23",
    # 清明节
    "2026-04-04", "2026-04-05", "2026-04-06",
    # 劳动节
    "2026-05-01", "2026-05-02", "2026-05-03", "2026-05-04", "2026-05-05",
    # 端午节
    "2026-06-19", "2026-06-20", "2026-06-21",
    # 中秋节
    "2026-09-25", "2026-09-26", "2026-09-27",
    # 国庆节
    "2026-10-01", "2026-10-02", "2026-10-03", "2026-10-04", "2026-10-05",
    "2026-10-06", "2026-10-07",
}


def is_trade_day(d: dt.date) -> bool:
    """是否为 A 股交易日（周末或休市日返回 False）。"""
    if d.weekday() >= 5:  # 周六日
        return False
    if d.strftime("%Y-%m-%d") in HOLIDAYS_2026:
        return False
    return True


def latest_trade_day(from_date: dt.date | None = None) -> dt.date:
    """从给定日期（默认今天）向前回溯到最近一个交易日。"""
    d = from_date or dt.date.today()
    while not is_trade_day(d):
        d -= dt.timedelta(days=1)
    return d
